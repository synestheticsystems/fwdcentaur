#!/usr/bin/env python3
"""What a wallboard build is: the commit it was built from, and a digest of every file it is built
from, committed or not, so that any change to them makes another build. A card's revision means
something only within one build, and the wallboard's history and diagnostics tell builds apart by
this digest alone. scripts/build-wallboard.sh runs this to write the bundle's build-info.json and
the module the runtime reads the same identity from."""
import hashlib
import json
from pathlib import Path
import subprocess
import sys

# What the bundle is built from: the web crate and the core it builds on; the root manifest, whose
# workspace settings and dependencies fwd-core inherits; the settings contract, which the build turns
# into a module and Rust compiles in; the sounds the bundle carries; the build itself; and the Cargo
# configuration, toolchain and license the build reads or copies. The launcher beside the bundle and
# the wallboard's checks are no part of it, so that changing them makes no new build.
# test_wallboard_identity.py checks that these hold every manifest Cargo reads for the build.
INPUTS = ('crates/fwd-core', 'crates/fwd-web', 'Cargo.toml', 'deploy/wallboard/wallboard-contract.json',
          'deploy/wallboard/sounds', 'scripts/build-wallboard.sh', 'scripts/wallboard_identity.py',
          '.cargo/config.toml', 'rust-toolchain.toml', 'LICENSE')


def inputs(repo):
    """The files of INPUTS in the checkout at `repo` that Git does not ignore, committed or not."""
    listed = subprocess.run(['git', 'ls-files', '-z', '--cached', '--others', '--exclude-standard', '--', *INPUTS],
                            cwd=repo, check=True, capture_output=True, text=True).stdout.split('\0')
    return sorted(name for name in set(listed) - {''} if (repo / name).is_file())


def content_sha256(repo):
    digest = hashlib.sha256()
    for name in inputs(repo):
        digest.update(f'{name}\0{hashlib.sha256((repo / name).read_bytes()).hexdigest()}\n'.encode())
    return digest.hexdigest()


def main():
    repo = Path(sys.argv[1])
    revision = subprocess.run(['git', 'rev-parse', 'HEAD'], cwd=repo, check=True, capture_output=True, text=True)
    identity = {'source_revision': revision.stdout.strip(), 'content_sha256': content_sha256(repo)}
    (repo / 'deploy/wallboard/build-info.json').write_text(json.dumps(identity, indent=2) + '\n')
    (repo / 'crates/fwd-web/src/wallboard/wallboard-build.mjs').write_text(
        '// Generated by scripts/build-wallboard.sh: what this build is, and nothing of a display or project.\n'
        f'export const buildInfo = {json.dumps(identity)};\n')


if __name__ == '__main__':
    main()
