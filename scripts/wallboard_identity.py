#!/usr/bin/env python3
"""What a wallboard build is: the commit it was built from, and a digest of every file it is built
from, committed or not, so that any change to them makes another build. A card's revision means
something only within one build, and the wallboard's history and diagnostics tell builds apart by
this digest alone. scripts/build-wallboard.sh runs this twice: `identify`, before trunk, writes the
module the runtime reads this build's identity from and prints the identity; `record`, once the
bundle's dist is in place, writes the same identity into the bundle's build-info.json, but not for a
dist that carries another build's module, so that build-info.json never names a page built under
another identity."""
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys

# What the bundle is built from: the web crate and the core it builds on; the root manifest, whose
# workspace settings and dependencies fwd-core inherits; the settings contract, which the build turns
# into a module and Rust compiles in; the sounds the bundle carries; the build itself, with what writes
# its notice; and the Cargo configuration, toolchain and license the build reads or copies. The launcher beside the bundle and
# the wallboard's checks are no part of it, so that changing them makes no new build.
# test_wallboard_identity.py checks that these hold every manifest Cargo reads for the build.
INPUTS = ('crates/fwd-core', 'crates/fwd-web', 'Cargo.toml', 'deploy/wallboard/wallboard-contract.json',
          'deploy/wallboard/sounds', 'scripts/build-wallboard.sh', 'scripts/wallboard_identity.py',
          'scripts/wallboard_notices.py', '.cargo/config.toml', 'rust-toolchain.toml', 'LICENSE')


def inputs(repo):
    """The files of INPUTS in the checkout at `repo` that Git does not ignore, committed or not."""
    listed = subprocess.run(['git', 'ls-files', '-z', '--cached', '--others', '--exclude-standard', '--', *INPUTS],
                            cwd=repo, check=True, capture_output=True, text=True).stdout.split('\0')
    return sorted(name for name in set(listed) - {''} if (repo / name).is_file())


def content_sha256(repo):
    digest = hashlib.sha256()
    for name in inputs(repo):
        digest.update(f'{name}\0{hashlib.sha256((repo / name).read_bytes()).hexdigest()}\n'.encode())
    return digest.hexdigest()


def module(identity):
    """The module the runtime imports `identity` from, wallboard-build.mjs, as the build writes it into
    crates/fwd-web/src/wallboard and the bundle's dist carries it."""
    return ('// Generated by scripts/build-wallboard.sh: what this build is, and nothing of a display or project.\n'
            f'export const buildInfo = {json.dumps(identity)};\n')


def identify(repo):
    """Writes the module the runtime reads this build's identity from, and returns the identity."""
    revision = subprocess.run(['git', 'rev-parse', 'HEAD'], cwd=repo, check=True, capture_output=True, text=True)
    identity = {'source_revision': revision.stdout.strip(), 'content_sha256': content_sha256(repo)}
    (repo / 'crates/fwd-web/src/wallboard/wallboard-build.mjs').write_text(module(identity))
    return identity


def record(bundle, identity):
    """Writes `identity` as the build-info.json of the bundle in `bundle`, whose dist must carry the
    module of that identity and no other. Raises ValueError, and writes nothing, for a dist that
    carries no such module or one of another build. The file is written whole beside its name and
    then moved onto it, so that a write that fails, as on a full disk, leaves no build-info.json."""
    dist, expected = bundle / 'dist', module(identity)
    carried = sorted(dist.rglob('wallboard-build.mjs'))
    if not carried:
        raise ValueError(f'{dist} carries no wallboard-build.mjs: it names no build for build-info.json to record')
    for path in carried:
        if path.read_text() != expected:
            raise ValueError(f'{path} is not the module of the build with content_sha256 '
                             f'{identity["content_sha256"]}: the dist was built under another identity')
    written = bundle / '.build-info.json.partial'
    try:
        written.write_text(json.dumps(identity, indent=2) + '\n')
        os.replace(written, bundle / 'build-info.json')
    finally:
        # Gone once it has been moved; left only by a write that failed.
        written.unlink(missing_ok=True)


def main():
    command, *arguments = sys.argv[1:] or ['']
    if command == 'identify' and len(arguments) == 1:
        print(json.dumps(identify(Path(arguments[0]))))
    elif command == 'record' and len(arguments) == 2:
        identity = json.loads(arguments[1])
        try:
            record(Path(arguments[0]), identity)
        except ValueError as refusal:
            sys.exit(f'build-info.json is not written: {refusal}')
    else:
        sys.exit('usage: wallboard_identity.py identify <repo> | record <bundle> <identity as JSON>')


if __name__ == '__main__':
    main()
